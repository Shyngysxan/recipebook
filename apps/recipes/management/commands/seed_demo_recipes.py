TITLES = [d[0] for d in DEMO]


class Command(BaseCommand):
    help = "Демо-рецепттер қосады (9-апта: сүзгі/іздеу/пагинацияны тексеру үшін)"

    def add_arguments(self, parser):
        parser.add_argument("--clear", action="store_true", help="демо-рецепттерді өшіру")

    def handle(self, *args, **options):
        if options["clear"]:
            deleted, _ = Recipe.objects.filter(title__in=TITLES).delete()
            self.stdout.write(self.style.WARNING(f"Өшірілді (пікірлерімен қоса): {deleted}"))
            return

        now = timezone.now()
        created = 0
        for i, (title, cat, cui, diff, minutes, servings, ingredients, instructions) in enumerate(DEMO, start=1):
            category, _ = Category.objects.get_or_create(name=cat)
            cuisine, _ = Cuisine.objects.get_or_create(name=cui)
            recipe, is_new = Recipe.objects.get_or_create(
                title=title,
                defaults=dict(category=category, cuisine=cuisine, difficulty=diff, cooking_time=minutes,
                              servings=servings, ingredients=ingredients, instructions=instructions,
                              description=f"{title} – демо-рецепт."))
            if is_new:
                # created_at auto_now_add, сондықтан update() арқылы әртүрлі күн қоямыз
                Recipe.objects.filter(pk=recipe.pk).update(created_at=now - timedelta(days=i, hours=i))
                created += 1
        self.stdout.write(self.style.SUCCESS(
            f"Жаңа рецепт: {created}. Барлық рецепт саны: {Recipe.objects.count()}"))
